#include <stdio.h>

int main()
{
    // == igualdade
    // != diferenca
    // < menor
    // > maior
    // <= menor ou igual
    // >= maior ou igual

    printf("2 == 5? %i\n", 2 == 5);
    printf("2 != 5? %i\n", 2 != 5);
    printf("2 <= 5? %i\n", 2 <= 5);
    printf("2 > 5? %i\n", 2 > 5);
    printf("2 >= 5? %i\n", 2 >= 5);

    return 0;
}