#include <stdio.h>

int main ()
{
    int idade = 27;
    printf("Idade: %i\n", idade);

    float altura = 1.70;
    printf("Altura: %.2f\n", altura);

    char tecla = 'A';
    printf("Tecla: %c\n", tecla);

    double numero_e = 2.7182818284;
    printf("Numero de Euler = %.10f\n", numero_e);

    return 0;
}